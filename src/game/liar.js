export function liarCategory(key) {
  return LIAR_CATEGORIES.find((c) => c.key === key) || LIAR_CATEGORIES[0]
}

// 같은 카테고리에서 서로 다른 두 단어를 뽑음 [다수 단어, 라이어 단어]
export function pickLiarWords(key) {
  const words = liarCategory(key).words
  const a = Math.floor(Math.random() * words.length)
  let b = Math.floor(Math.random() * (words.length - 1))
  if (b >= a) b += 1
  return [words[a], words[b]]
}
